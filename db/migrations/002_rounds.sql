-- 002_rounds.sql - round history + per-player results. round_uuid is the natural idempotency key.
-- Applied in order by schema_migrations. Recording must never fail because a guest lacked identity,
-- so player references here carry no FK (winners/players can be bots or anonymous guests).

CREATE TABLE IF NOT EXISTS rounds (
  round_uuid        TEXT PRIMARY KEY,           -- generated by the server at round start
  room_code         TEXT NOT NULL,
  started_at        TIMESTAMPTZ NOT NULL,
  ended_at          TIMESTAMPTZ NOT NULL,
  duration_s        INT NOT NULL,
  bot_level         TEXT NOT NULL DEFAULT 'normal',
  humans_count      INT NOT NULL,
  winner_id         TEXT,                       -- no FK: winner can be a bot
  end_reason        TEXT NOT NULL,
  eligible          BOOLEAN NOT NULL DEFAULT false,
  ineligible_reason TEXT,
  recorded_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_rounds_ended ON rounds(ended_at);

CREATE TABLE IF NOT EXISTS round_players (
  round_uuid  TEXT NOT NULL REFERENCES rounds(round_uuid) ON DELETE CASCADE,
  player_id   TEXT NOT NULL,                    -- no FK: guests/bots may have no identity row
  result      TEXT NOT NULL,                    -- 'win' | 'lose' | ...
  powers_used INT NOT NULL DEFAULT 0,
  deposits    INT NOT NULL DEFAULT 0,
  searches    INT NOT NULL DEFAULT 0,
  PRIMARY KEY (round_uuid, player_id)
);
